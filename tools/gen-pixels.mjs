#!/usr/bin/env node
// Rasterizes every flag SVG into a quantized palette grid, using headless
// Firefox as the renderer. Writes js/pixels.js.
import fs from 'node:fs';
import path from 'node:path';
import { serve, newSession } from './webdriver.mjs';
import { ROOT } from './harness.mjs';

const BATCH = 8;

const { close: closeServer, url } = await serve(8732);
const d = await newSession({ headless: true, driverPort: 4446 });

try {
  // A fine grid means a lot of sampling per batch; the 30s default would fire
  // long before a batch finishes.
  await d.setTimeouts({ script: 600000 });
  await d.go(`${url}/tools/pixelgen.html`);
  await d.waitFor('typeof window.buildBatch === "function"', { label: 'generator page' });
  const total = await d.execute('return window.total;');
  const dims = await d.execute('return [window.Palette.GRID_W, window.Palette.GRID_H];');

  const grids = {};
  for (let start = 0; start < total; start += BATCH) {
    const part = await d.executeAsync(
      `var done = arguments[arguments.length - 1];
       window.buildBatch(arguments[0], arguments[1]).then(done, function (e) { done({ __error: String(e) }); });`,
      [start, BATCH]
    );
    if (part.__error) throw new Error(part.__error);
    Object.assign(grids, part);
    process.stdout.write(`\r  rasterizing ${Object.keys(grids).length}/${total}`);
  }
  process.stdout.write('\n');

  const codes = Object.keys(grids).sort();
  const body = codes.map((c) => `  ${c}: "${grids[c]}"`).join(',\n');
  const js = `// Auto-generated by tools/gen-pixels.mjs — do not edit by hand.
// Each flag is a ${dims[0]}x${dims[1]} row-major grid of js/palette.js colour
// indices, run-length coded (see Palette.encodeRLE).
window.FLAG_PIXELS_RLE = {
${body}
};

// Expanded once at load: FLAG_PIXELS[code] is a Uint8Array of ${dims[0] * dims[1]} cells.
window.FLAG_PIXELS = window.Palette.expandAll(window.FLAG_PIXELS_RLE);
`;
  fs.writeFileSync(path.join(ROOT, 'js', 'pixels.js'), js);
  const raw = (codes.length * dims[0] * dims[1]) / 1024;
  console.log(
    `wrote js/pixels.js — ${codes.length} grids at ${dims[0]}x${dims[1]}, ` +
      `${(js.length / 1024).toFixed(1)} KB coded (${raw.toFixed(0)} KB raw)`
  );
} finally {
  await d.quit();
  closeServer();
}
